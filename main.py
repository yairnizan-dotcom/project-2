import streamlit as st
import time
import random

# הגדרת תצורת דף חגיגית להוליווד
st.set_page_config(page_title="Hollywood Tycoon AI", page_icon="🎬", layout="centered")

# --- כותרת ראשית וחוקי המשחק ---
st.title("🎬 Hollywood Tycoon: משחק הסימולציה הקולנועי")
st.markdown("""
### 🎥 ברוך הבא, תסריטאי ובמאי מתחיל!
חברת ההפקה הגדולה בעולם נתנה לך צ'ק פתוח להפיק את סרט החלומות שלך. 
האם תצליח ליצור **שוברי קופות (Blockbuster)** מטורף, או שתקבור את האולפן בחובות ותסיים את הקריירה?

**המטרה:** להגיע לרווח המקסימלי האפשרי על ידי איזון נכון בין התקציב לבין מדד הפופולריות והבאזז הציבורי שהסרט מייצר!
""")

st.divider()

# --- שלב 1: פרטי הסרט והיצירתיות ---
st.header("📝 שלב א': כתיבת התסריט והקונספט")

movie_name = st.text_input("💡 מהו שם הסרט שלך?", placeholder="לדוגמה: אווטאר 3: נקמתו של ג'אר ג'אר")

genre = st.selectbox("🎭 בחר ז'אנר מוביל:", [
    "מדע בדיוני וחלל 🚀", 
    "אקשן מפוצץ ומכוניות מהירות 💥", 
    "קומדיה רומנטית קיטשית 🍿", 
    "אימה פסיכולוגי במרתף חשוך 👻", 
    "דרמה סוחטת דמעות לאוסקר 🏆"
])

# --- שלב 2: הקצאת המשאבים (הקלט למודל) ---
st.header("💰 שלב ב': תקציב מול באזז תקשורתי")

# מאפיין 2: תקציב (נשמר בדיוק אותו דבר)
budget = st.number_input(
    "💵 כמה כסף האולפן משקיע בהפקה ובאפקטים? (בדוֹלָרִים):", 
    min_value=0.0, 
    value=50000000.0, 
    step=1000000.0,
    format="%f"
)

# מאפיין 1: פופולריות / באזז (טווח 1 עד 10)
popularity = st.slider(
    "🔥 כמה באזז ופופולריות הסרט מייצר ברשתות (מ-1 עד 10)?", 
    min_value=1.0, 
    max_value=10.0, 
    value=5.0,
    help="מדד גבוה דורש תסריט גאוני או שיווק אגרסיבי!"
)

# --- כפתור ההפעלה (ערב הפרמיירה) ---
st.divider()
predict_button = st.button("אל אולם הקולנוע! 🚀 הקרנת בכורה חגיגית")

# --- מנוע החיזוי והמשחק ---
if predict_button:
    if not movie_name:
        st.warning("⚠️ רגע! אי אפשר להוציא סרט בלי שם. תן לו כותרת מפוצצת!")
    else:
        # אפקט מתח קולנועי
        with st.spinner('🍿 הקהל נכנס לאולם... הפופקורן מוכן... האורות כבים...'):
            time.sleep(1.5)
        st.toast("🎬 הסרט מוקרן כעת ברחבי העולם!")
        time.sleep(1)
            
        # --- משקולות המודל המקוריות (נשמרו במדויק) ---
        w_popularity = 1605154.4964212137
        w_budget = 2.6858848237184723
        b = -25644372.266467094
        
        # התאמת קנה מידה (Scaling) המקורית
        scaled_popularity = popularity * 20
        
        # חישוב החיזוי לפי הנוסחה המקורית
        estimated_revenue = (w_popularity * scaled_popularity) + (w_budget * budget) + b
        display_revenue = max(0.0, estimated_revenue)
        
        # --- מסך התוצאות והפידבק המשחקי ---
        st.subheader("📊 דוח רווחי הקופות הרשמי")
        
        # הצגת התוצאה במדד מטרי
        st.metric(label="💰 סך הכנסות בקופות הגלובליות", value=f"${display_revenue:,.0f}")
        
        # חישוב אחוז הרווח ביחס לתקציב כדי לתת ציון למשחק
        if budget > 0:
            profit_ratio = display_revenue / budget
        else:
            profit_ratio = 0

        # התאמת תגובת ה-AI לפי הצלחת השחקן
        if display_revenue == 0:
            st.error(f"💀 **קסטסטרופה הוליוודית!** הסרט '{movie_name}' התרסק לחלוטין. המבקרים קטלו, האולם ריק, ואתה כנראה תביים עכשיו רק פרסומות למיונז.")
        elif profit_ratio < 1.0:
            st.warning(f"📉 **כישלון קופתי משבר תקציבי!** הסרט הכניס כסף, אבל לא כיסה את ההשקעה הגבוהה של ${budget:,.0f}. האולפנים כועסים עליך.")
        elif profit_ratio <= 1.5:
            st.info(f"😐 **סרט סביר (Cult Classic):** החזרת את ההשקעה בקושי. המעריצים אוהבים את זה, אבל המפיקים ציפו ליותר מבעל ז'אנר כמו {genre}.")
        elif profit_ratio <= 3.0:
            st.success(f"⭐ **להיט קולנועי!** עבודה יפה! הסרט '{movie_name}' הפך להצלחה מסחרית יפה מאוד ברחבי העולם. קבל כרטיס חבר VIP להוליווד!")
        else:
            st.balloons()
            st.success(f"👑 **מאסטר הוליווד! שובר קופות היסטורי!** הסרט שלך הוא תופעה תרבותית! המפיקים מתחננים כבר לסרט המשך, ואתה בדרך לטקס האוסקר!")

        # פירוט המדדים הטכנולוגיים המקוריים בשפה משחקית
        with st.expander("🧐 לראות את מאחורי הקלעים (נתוני המודל):"):
            st.write(f"הנוסחה שקללה פופולריות מותאמת של **{scaled_popularity:.0f} אל מול תקציב של **${budget:,.0f}**.")
            st.write("המשקולות נותרו יציבות ומדויקות לפי מודל ה-AI המקורי שלך.")
